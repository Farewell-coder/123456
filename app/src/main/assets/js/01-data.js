function dbPool(stage){
  // 走统一内容库（内置 + 覆盖层），事件字段已规范化为 stage/age/weight/text/effects
  /* 需求 27：性别过滤 —— 「通用」事件人人可遇，专属事件只给对应性别。
     角色没定性别时（老存档 / 测试）按通用处理，等价于不过滤。 */
  const me = (S && S.sex) || '通用';
  const list = dataOf('ev').filter(x => x.stage === stage)
    .filter(x => { const sx = evSex(x); return sx === '通用' || sx === me; });
  if(!list.length) return null;
  const rows = list.map(r => ({t:r.text, e:r.effects || {}, w:r.weight || 5,
    lo:r.age[0], hi:r.age[1], id:r.id, tags:(r.tags || []).slice(),
    aff:(r.aff && r.aff.length) ? r.aff.slice() : null,
    /* 需求 27：性别编号（隐藏）—— 池子已按性别过滤过，这里透传是为了同签名随机去重 */
    sex: evSex(r),
    /* patch54：需求向量 / 子项增量 / 峰值年龄 / 一生一次 —— 全部可选 */
    req: r.req || null, subs: r.subs || null,
    peak: (r.peak == null ? null : r.peak), once: !!r.once}));
  /* 已经拥有该标签的事件不再重复出现 —— 不然会出现「又解锁了一次房贷」这种重复感。
     现成标签事件全是 patch43 新加的（老库里 tags 一律为空），所以旧行为不受影响。 */
  if(S && Array.isArray(S.tags) && S.tags.length){
    const have = S.tags;
    const filtered = rows.filter(r => !(r.tags && r.tags.length &&
      r.tags.every(t => have.indexOf(t) >= 0)));
    if(filtered.length) return filtered;
  }
  return rows;
}
/* 年龄 -> 数据库阶段名 */
function dbStageOf(a){
  if(a <= 3) return '幼年';
  if(a <= 12) return '童年';
  if(a <= 18) return '少年';
  if(a <= 30) return '青年';
  if(a <= 60) return '中年';
  return '老年';
}
/* ===== 需求 28：同款随机去重 =====
   「性别编号 + 属性数值」完全相同的条目视为同一款（换词不换事）。
   抽到时不在它们之间比权重，而是随机取一条 —— 避免同款桥段反复出现。
   签名只取性别、effects、aff 三项，不含文案本身。 */
function evSign(x){
  if(!x) return '';
  const e = x.e || x.effects || {};
  const ks = Object.keys(e).sort();
  let h = String(x.sex || '通用') + '|';
  ks.forEach(k => { h += k + ':' + (Number(e[k]) || 0) + ','; });
  h += '|' + (x.aff ? [].concat(x.aff).slice().sort().join('') : '');
  return h;
}
/* 在同签名的候选里随机取一条：优先还没出现过的，都出现过了才回落到全体 */
function sigPick(x, pool){
  if(!x || !pool || pool.length < 2) return x;
  const s = evSign(x);
  const same = pool.filter(y => evSign(y) === s);
  if(same.length < 2) return x;
  const fresh = same.filter(y => !evStamp[y.t]);
  const cand = fresh.length ? fresh : same;
  return cand[Math.floor(Math.random() * cand.length)];
}
/* 本局每个事件「最后一次出现」的全局序号；没出现过的记为 0 */
let evStamp = {};
let evTick = 0;
/* 最近若干年刚出现过的文案：保证相邻年份绝不重样 */
let evRecent = [];
const EV_RECENT_WIN = 8;
/* 需求 D：AI 自己写过的文案窗口 —— 让 AI 能看到前几年写过什么，
   否则它每次请求都是「失忆」状态，写出来的年度事件各说各话 */
